def _r_vector(items: list[str]) -> str:
    return "c(" + ", ".join(json.dumps(x) for x in items) + ")" if items else "character()"


def install_source(v: dict, entry: dict) -> str:
    repo = v["repo"]
    if entry["kernel"] == "python3":
        pins = common.python_pins(v, entry)
        return (
            PY_INSTALL.replace("__NOTICE__", CODE_NOTICE)
            .replace("__REF__", str(repo["ref"]))
            .replace("__REPO__", repo["url"])
            .replace("__PINS__", repr(pins))
            .replace("__CONSTRAINTS__", f"{repo['raw']}/{repo['ref']}/environment/requirements.txt")
        )
    r = common.r_install(v, entry)
    pairs = [
        f"{n} = c({json.dumps(rs)}, {json.dumps(sha)})" for n, (rs, sha) in r["github"].items()
    ]
    github = "list(" + ", ".join(pairs) + ")"
    return (
        R_INSTALL.replace("__NOTICE__", CODE_NOTICE)
        .replace("__REF__", str(repo["ref"]))
        .replace("__RAW__", repo["raw"])
        .replace("__CRAN__", _r_vector(r["cran"]))
        .replace("__GITHUB__", github)
        .replace("__GSL__", "TRUE" if r["gsl"] else "FALSE")
        .replace("__P3M__", r["p3m_url"])
    )


def harness_source(v: dict, entry: dict, body: list) -> str:
    content = common.sha_of_cells(body)
    deps = common.deps_sha(v, entry)
    ref = str(v["repo"]["ref"])
    if entry["kernel"] == "python3":
        exercises = exercises_python(body)
        return "\n".join(
            [
                '# @title Workshop harness: run this cell first { display-mode: "form" }',
                CODE_NOTICE,
                "# WORKED_EXAMPLE runs every reference solution in place of your code: a",
                "# complete worked example, not a sign that you did the exercises. QUICK shortens",
                "# long steps (sampling, data size).",
                'WORKED_EXAMPLE = False  # @param {type:"boolean"}',
                'QUICK = False  # @param {type:"boolean"}',
                "",
                "from mktstats import checks",
                "from mktstats.harness import start as _start",
                "",
                "workshop = _start(",
                f"    notebook={entry['id']!r},",
                f"    content_sha={content!r},",
                f"    deps_sha={deps!r},",
                f"    ref={ref!r},",
                f"    exercises={exercises!r},",
                ")",
            ]
        )
    exercises = exercises_r(body)
    items = ", ".join(f"`{n}` = {_r_vector(list(names))}" for n, names in sorted(exercises.items()))
    return "\n".join(
        [
            CODE_NOTICE,
            "# WORKED_EXAMPLE <- TRUE runs every reference solution in place of your code: a",
            "# complete worked example, not a sign that you did the exercises. QUICK <- TRUE",
            "# shortens long steps (sampling, data size).",
            "WORKED_EXAMPLE <- FALSE",
            "QUICK <- FALSE",
            ".ws_start(",
            f'  notebook = "{entry["id"]}",',
            f'  content_sha = "{content}",',
            f'  deps_sha = "{deps}",',
            f'  ref = "{ref}",',
            f"  exercises = list({items})",
            ")",
        ]
    )


def record_source(entry: dict) -> str:
    comment = (
        "# Which checkpoints passed, and on whose code; then the run record (also saved as"
        " run_record.json)."
    )
    if entry["kernel"] == "python3":
        return "\n".join([CODE_NOTICE, comment, "workshop.summary()", "workshop.run_record()"])
    return "\n".join([CODE_NOTICE, comment, "workshop_summary()", "run_record()"])


def next_notebook(v: dict, entry: dict) -> dict | None:
    """The next notebook in the same language, else the next one at all."""
    order = common.notebooks(v)
    later = [e for e in order if (e["n"], e["index"]) > (entry["n"], entry["index"])]
    same = [e for e in later if e["language"] == entry["language"]]
    return (same or later or [None])[0]


def footer_source(v: dict, entry: dict) -> str:
    site = v["repo"]["site"].rstrip("/")
    nxt = next_notebook(v, entry)
    lines = [NOTICE, "---"]
    if nxt is None:
        lines.append("**This is the last notebook.**")
    else:
        title = f"Module {nxt['n']} · {v['modules'][nxt['module']]['title']}"
        lang = LANGUAGE_NAMES[nxt["language"]]
        if (ROOT / nxt["path"]).exists():
            lines.append(f"**Next:** [{title}]({colab_url(v, nxt['path'])}) ({lang})")
        else:
            lines.append(f"**Next:** {title} ({lang}, in preparation)")
    lines += [
        "",
        f"[Workshop site]({site}/) · [All notebooks]({site}/notebooks.html) ·"
        f" [Source]({v['repo']['url']})",
        "",
        f"{v['workshop']['org']} · text CC BY 4.0, code MIT",
    ]
    return "\n".join(lines)


def _generated_markdown(cell_id: str, source: str):
    cell = nbformat.v4.new_markdown_cell(source)
    cell["id"] = cell_id
    cell["metadata"] = nbformat.NotebookNode({"tags": ["generated"]})
    return cell


def _generated_code(cell_id: str, source: str, form: bool):
    cell = nbformat.v4.new_code_cell(source)
    cell["id"] = cell_id
    cell["metadata"] = nbformat.NotebookNode({"tags": ["generated"]})
    if form:
        cell["metadata"]["cellView"] = "form"
    return cell


def build(v: dict, entry: dict):
    body = read_source(entry)
    python = entry["kernel"] == "python3"
    nb = nbformat.v4.new_notebook()
    nb.cells = [
        _generated_markdown(HEADER_ID, header_source(v, entry)),
        _generated_code(INSTALL_ID, install_source(v, entry), form=python),
        _generated_code(HARNESS_ID, harness_source(v, entry, body), form=python),
        *body,
        _generated_code(RECORD_ID, record_source(entry), form=False),
        _generated_markdown(FOOTER_ID, footer_source(v, entry)),
    ]
    k = KERNELS[entry["kernel"]]
    nb.metadata = nbformat.NotebookNode(
        {
            "colab": {"provenance": [], "toc_visible": True},
            "kernelspec": dict(k["kernelspec"]),
            "language_info": dict(k["language_info"]),
        }
    )
    nb.nbformat, nb.nbformat_minor = 4, 5
    nbformat.validate(nb)
    return nb


def render(nb) -> str:
    text = nbformat.writes(nb, version=4)
    return text if text.endswith("\n") else text + "\n"


def check_layout(v: dict) -> list[str]:
    """Problems with the notebook list itself: sources in the wrong place, orphans."""
    problems = []
    declared = set()
    for e in common.notebooks(v):
        k = KERNELS[e["kernel"]]
        path, source = Path(e["path"]), Path(e["source"])
        declared.add(e["path"])
        if path.parent != Path("labs") / k["dir"] or path.suffix != ".ipynb":
            problems.append(f"{e['path']}: a {e['kernel']} notebook belongs in labs/{k['dir']}/")
        if source.parent != Path("labs/src") or source.suffix != k["ext"]:
            problems.append(f"{e['source']}: a {e['kernel']} source is labs/src/*{k['ext']}")
        if path.stem != source.stem:
            problems.append(f"{e['path']}: its source {e['source']} has another name")
    for d in ("python", "r"):
        for p in sorted((ROOT / "labs" / d).glob("*.ipynb")):
            rel = p.relative_to(ROOT).as_posix()
            if rel not in declared:
                problems.append(f"{rel}: not declared in _variables.yml modules.*.notebooks")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if anything would change")
    args = parser.parse_args(argv)
    v = common.load_variables()
    problems = check_layout(v)
    drift = []
    for entry in common.notebooks(v):
        if not (ROOT / entry["source"]).exists():
            if (ROOT / entry["path"]).exists():
                problems.append(f"{entry['path']}: its source {entry['source']} is missing")
            continue
        text = render(build(v, entry))
        out = ROOT / entry["path"]
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if current == text:
            continue
        drift.append(entry["path"])
        if not args.check:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
            print(f"wrote {entry['path']}")
    if problems:
        print("\n".join(problems))
        return 1
    if args.check and drift:
        print("Generated notebooks are out of date (run python scripts/gen_notebooks.py):")
        print("\n".join(f"  {p}" for p in drift))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
