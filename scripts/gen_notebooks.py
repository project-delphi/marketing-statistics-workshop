# ---- reading a source --------------------------------------------------------------------


def read_source(entry: dict) -> list:
    """The source's cells as nbformat cells: tags kept, everything else normalized."""
    fmt = KERNELS[entry["kernel"]]["fmt"]
    nb = jupytext.read(ROOT / entry["source"], fmt=fmt)
    cells = []
    for cell in nb.cells:
        source = cell.source.strip("\n").rstrip()
        if not source.strip():
            continue
        tags = list(cell.metadata.get("tags", []))
        if cell.cell_type == "markdown":
            new = nbformat.v4.new_markdown_cell(source)
        else:
            new = nbformat.v4.new_code_cell(source)
        new.metadata = nbformat.NotebookNode({})
        if tags:
            new.metadata["tags"] = tags
        if "solution" in tags:
            new.metadata["cellView"] = "form"
            new.metadata["jupyter"] = {"source_hidden": True}
        cells.append(new)
    for i, cell in enumerate(cells):
        cell["id"] = f"cell-{i:03d}"
    return cells


def exercises_python(cells: list) -> dict:
    """{n: (names...)} from @workshop.solution(n) and workshop.solution_value(n, "name", ...)."""
    out: dict = {}
    for cell in cells:
        if cell.cell_type != "code" or "solution" not in cell.metadata.get("tags", []):
            continue
        try:
            tree = ast.parse(cell.source)
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                for dec in node.decorator_list:
                    if (
                        isinstance(dec, ast.Call)
                        and isinstance(dec.func, ast.Attribute)
                        and dec.func.attr == "solution"
                        and isinstance(dec.func.value, ast.Name)
                        and dec.func.value.id == "workshop"
                        and dec.args
                        and isinstance(dec.args[0], ast.Constant)
                    ):
                        out.setdefault(dec.args[0].value, []).append(node.name)
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and node.func.attr == "solution_value"
                and len(node.args) >= 2
                and isinstance(node.args[0], ast.Constant)
                and isinstance(node.args[1], ast.Constant)
            ):
                out.setdefault(node.args[0].value, []).append(node.args[1].value)
    ordered = sorted(out.items(), key=lambda kv: kv[0])
    return {n: tuple(dict.fromkeys(names)) for n, names in ordered}


R_SOLUTION = re.compile(r"^\s*solution\(\s*(\d+)\s*,\s*[\"']([^\"']+)[\"']", re.M)


def exercises_r(cells: list) -> dict:
    out: dict = {}
    for cell in cells:
        if cell.cell_type != "code" or "solution" not in cell.metadata.get("tags", []):
            continue
        for n, name in R_SOLUTION.findall(cell.source):
            out.setdefault(int(n), []).append(name)
    return {n: tuple(dict.fromkeys(names)) for n, names in sorted(out.items())}


# ---- the generated cells -----------------------------------------------------------------


def colab_url(v: dict, path: str) -> str:
    return f"{v['repo']['colab_base']}/{v['repo']['ref']}/{path}"


def stack(v: dict, entry: dict) -> str:
    lang = LANGUAGE_NAMES[entry["language"]]
    version = v["environment"]["python" if entry["language"] == "python" else "r"]
    names = list(entry["install"])
    return ", ".join([f"{lang} {version}", *names])


def header_source(v: dict, entry: dict) -> str:
    m = v["modules"][entry["module"]]
    day = v["days"][m["day"]]
    lab = m["minutes"]["lab"]
    when = day["label"]
    optional = " (optional pre-work)" if m.get("optional") else ""
    lines = [
        NOTICE,
        f"# Module {entry['n']} · {m['title']}",
        "",
        f"[![Open in Colab]({BADGE})]({colab_url(v, entry['path'])})",
        "",
        f"**{v['workshop']['title']}** · {when} · {LANGUAGE_NAMES[entry['language']]}"
        f" · {lab}-minute lab{optional}",
        "",
        m.get("summary") or "*Summary to be written.*",
        "",
    ]
    objectives = m.get("objectives") or []
    if objectives:
        lines += ["**By the end of this notebook you can:**", ""]
        lines += [f"- {o}" for o in objectives]
    else:
        lines.append("*Objectives to be written.*")
    lines += ["", f"**Stack:** {stack(v, entry)}"]
    if m.get("decision"):
        lines += ["", f"**The decision:** {m['decision']}"]
    lines += [
        "",
        "**How this notebook works.** Run the cells in order (Runtime > Run all is fine: it stops"
        " at the first exercise you have not written). Each exercise has a stub to complete, a"
        " folded solution, and a checkpoint that says whether your code passed.",
    ]
    return "\n".join(lines)


