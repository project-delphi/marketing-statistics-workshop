def teaching_time(v: dict, entry: dict, records: list[dict]) -> str:
    env = readiness.teaching_env(v, entry["kernel"])
    mine = [
        r
        for r in records
        if r["notebook"] == entry["id"]
        and r["env"] == env
        and readiness.teaching_eligible(v, r)
        and r["status"] == "pass"
    ]
    r = readiness.newest(mine)
    if r is None:
        return "not yet timed on Colab"
    return f"{readiness.duration(r.get('seconds'))} on Colab ({r['date']})"


def notebooks_table(v: dict, records: list[dict]) -> str:
    envs = v["readiness"]["envs"]
    rows = [
        "| Module | Notebook | Language | Runtime | Open | Time on Colab |",
        "|---|---|---|---|---|---|",
    ]
    for e in common.notebooks(v):
        m = v["modules"][e["module"]]
        env = readiness.teaching_env(v, e["kernel"])
        runtime = envs[env]["label"] if env else "—"
        if exists(e):
            badge = f"[![Open in Colab]({BADGE})]({colab_url(v, e)})"
            time = teaching_time(v, e, records)
        else:
            badge, time = "in preparation", "—"
        rows.append(
            f"| [{module_number(e['module'])} · {m['title']}]({module_link(e['module'], m)})"
            f" | `{Path(e['path']).stem}` | {LANG[e['language']]} | {runtime} | {badge} | {time} |"
        )
    note = (
        "Times come from run records of a worked, full-settings run of the whole notebook on"
        " Colab ([readiness](/readiness.qmd)); laptop, Docker and CI times are never shown as"
        " Colab times."
    )
    return "\n".join(rows) + "\n\n" + note


def lane_text(v: dict, lane: dict) -> str:
    if lane["state"] == "documented":
        return "documented, not run"
    if lane["record"] is None:
        return "not run"
    return readiness.describe(lane["record"])


def readiness_summary(report: dict, link: str | None = "/readiness.qmd") -> str:
    s = report["summary"]
    if s["all_ready"] and s["ci_passed"] == s["notebooks"]:
        verdict = "ready to teach"
    elif s["all_ready"]:
        # CI records live on the evidence branch: a checkout without them must not claim more.
        verdict = ("Colab evidence complete; ready to teach once CI passes on the current code"
                   " (the live readiness page counts CI runs)")
    else:
        verdict = "not yet ready to teach"
    when = f"As of {s['as_of']}" if s["as_of"] else "No runs are recorded yet"
    not_written = s["notebooks"] - s["written"]
    parts = [
        f"**{when}: {verdict}.**",
        f"{s['ready']} of {s['notebooks']} notebooks have a current, passing, worked,"
        " full-settings run of the whole notebook on Colab"
        + (f" ({not_written} are not written yet)." if not_written else "."),
        f"{s['elsewhere_passed']} have passed on another machine"
        f" ({s['elsewhere_full']} with full settings), and {s['ci_passed']} on CI.",
    ]
    if link:
        parts.append(f"[What has run, where]({link}).")
    return " ".join(parts)


def readiness_page(v: dict, report: dict) -> str:
    envs = v["readiness"]["envs"]
    rows = ["| Notebook | Ready to teach | Evidence |", "|---|---|---|"]
    for e in report["notebooks"]:
        m = v["modules"][e["module"]]
        ready = "**Yes**" if e["ready"] else f"No: {e['why']}"
        lines = [f"**{envs[k]['label']}:** {lane_text(v, lane)}" for k, lane in e["lanes"].items()]
        if e["learner"] is not None:
            lr = e["learner"]
            verdict = (
                "stopped at checkpoint 1 as designed"
                if lr["status"] == "pass"
                else ("**did not stop as designed**")
            )
            lines.append(f"**Learner mode:** {verdict} ({lr['date']}, {envs[lr['env']]['label']})")
        name = (
            f"`{e['id']}`<br>[Module {module_number(e['module'])}]({module_link(e['module'], m)})"
        )
        rows.append(f"| {name} | {ready} | {'<br>'.join(lines)} |")
    s = report["summary"]
    legend = [
        "## How to read this page {#legend}",
        "",
        "Each evidence line is the newest worked run on that machine, from the run records in"
        f" [`runs/`]({v['repo']['url']}/tree/{v['repo']['ref']}/runs). A newer failure replaces an"
        " older pass. A run is *before the notebook or its deps last changed* when the"
        " notebook's code (content_sha) or the files, pins and ref it depends on (deps_sha) have"
        " changed since; it no longer counts.",
        "",
        "*Ready to teach* needs a passing run on Colab, the runtime the notebook is designed for:"
        " worked (reference solutions bound), the whole notebook, full settings (not QUICK),"
        f" with the current code and deps, at most {s['max_age']} days older than the newest"
        " record on this page. A laptop's, the Docker image's or the CI runner's time does not"
        " predict Colab's. The AWS paths are documented, not run.",
        "",
        "*Learner mode* runs the notebook with nothing written: it must stop at the first"
        " checkpoint with the message that tells a participant how to go on.",
    ]
    return "\n".join(
        [
            readiness_summary(report, link=None),
            "",
            "::: {.readiness-table}",
            "\n".join(rows),
            ":::",
            "",
            *legend,
        ]
    )


def install_times(v: dict, records: list[dict]) -> str:
    envs = v["readiness"]["envs"]
    rows = ["| Runtime | Notebook | Install and setup | Measured |", "|---|---|---|---|"]
    for key, env in envs.items():
        if not env.get("teaching"):
            continue
        measured = {}
        for r in records:
            if (
                r["env"] == key
                and r.get("install_seconds") is not None
                and r.get("runtime")
                in (
                    "colab",
                    "sagemaker",
                )
            ):
                best = measured.get(r["notebook"])
                if best is None or (r["date"], r.get("file", "")) > (
                    best["date"],
                    best.get("file", ""),
                ):
                    measured[r["notebook"]] = r
        if not measured:
            rows.append(f"| {env['label']} | — | not yet measured | — |")
        for nb_id, r in sorted(measured.items()):
            rows.append(
                f"| {env['label']} | `{nb_id}` | {readiness.duration(r['install_seconds'])}"
                f" | {r['date']} |"
            )
    note = (
        "Measured by each notebook's install cell on a fresh runtime and read from its run"
        " record. On your own machine or in the workshop's Docker image nothing is installed."
    )
    return "\n".join(rows) + "\n\n" + note


def sidebar(v: dict) -> str:
    sections = []
    for dkey, d in days(v):
        keys = day_modules(v, dkey)
        if not keys:
            continue
        sections.append(
            {
                "section": f"{d['label']} · {d['title']}",
                "contents": [
                    {
                        "href": f"modules/{v['modules'][k]['slug']}.qmd",
                        "text": f"{module_number(k)} · {v['modules'][k]['title']}",
                    }
                    for k in keys
                ],
            }
        )
    tree = {"website": {"sidebar": [{"id": "modules", "title": "Modules", "contents": sections}]}}
    head = "# GENERATED by scripts/gen_tables.py from _variables.yml. Do not edit by hand.\n"
    return head + yaml.safe_dump(tree, sort_keys=False, allow_unicode=True, width=1000)


