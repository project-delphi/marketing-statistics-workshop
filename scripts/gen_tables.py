def outputs(v: dict) -> dict[Path, str]:
    records = run_records.load_valid(v)
    report = readiness.build(v, records, readiness.newest_date(records))
    var_notice = NOTICE.format(src="_variables.yml")
    lab_notice = NOTICE.format(src="_variables.yml and the headings of labs/src")
    runs_notice = NOTICE.format(src="_variables.yml and the run records in runs/")
    files = {
        INCLUDES / "facts.md": (var_notice, facts(v)),
        INCLUDES / "days.md": (var_notice, days_cards(v)),
        INCLUDES / "path.md": (var_notice, path(v)),
        INCLUDES / "schedule.md": (var_notice, schedule(v)),
        INCLUDES / "notebooks.md": (runs_notice, notebooks_table(v, records)),
        INCLUDES / "readiness.md": (runs_notice, readiness_page(v, report)),
        INCLUDES / "readiness-summary.md": (runs_notice, readiness_summary(report)),
        INCLUDES / "install-times.md": (runs_notice, install_times(v, records)),
        ROOT / "environment" / "VERSIONS.md": (
            NOTICE.format(src="environment/requirements.txt and _variables.yml"),
            versions(v),
        ),
    }
    for dkey, _ in days(v):
        n = day_number(dkey)
        files[INCLUDES / f"day-{n}.md"] = (var_notice, module_cards(v, dkey))
        files[INCLUDES / f"run-{n}.md"] = (var_notice, run_sheet(v, dkey))
    for key, _ in modules(v):
        n = module_number(key)
        files[INCLUDES / f"module-{n:02d}.md"] = (var_notice, module_header(v, key))
        files[INCLUDES / f"lab-{n:02d}.md"] = (lab_notice, lab_block(v, key))
    out = {p: f"{notice}\n\n{body.rstrip()}\n" for p, (notice, body) in files.items()}
    out[INCLUDES / "sidebar.yml"] = sidebar(v)
    readme = ROOT / "README.md"
    if readme.exists():
        site = v["repo"]["site"].rstrip("/")
        status = "> " + readiness_summary(report, link=f"{site}/readiness.html")
        out[readme] = replace_region(readme.read_text(encoding="utf-8"), "status", status)
    return out


def replace_region(text: str, name: str, body: str) -> str:
    begin, end = f"<!-- BEGIN {name} -->", f"<!-- END {name} -->"
    if begin not in text or end not in text:
        return text
    head, rest = text.split(begin, 1)
    _, tail = rest.split(end, 1)
    return f"{head}{begin}\n{body.rstrip()}\n{end}{tail}"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if anything would change")
    args = parser.parse_args(argv)
    v = common.load_variables()
    drift = []
    for out, text in outputs(v).items():
        current = out.read_text(encoding="utf-8") if out.exists() else None
        if current == text:
            continue
        drift.append(out.relative_to(ROOT).as_posix())
        if not args.check:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text, encoding="utf-8")
    if args.check and drift:
        print("Generated files are out of date (run python scripts/gen_tables.py):")
        print("\n".join(f"  {p}" for p in drift))
        return 1
    if not args.check:
        print(f"{len(drift)} file(s) written" if drift else "Nothing to change")
    return 0


if __name__ == "__main__":
    sys.exit(main())
